import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const orchestrationDir = path.join(root, "docs", "runtime-orchestration");

const endpointSemantics = JSON.parse(
  fs.readFileSync(path.join(orchestrationDir, "endpoint-runtime-semantics.json"), "utf8"),
);
const runtimeStaticAnalysis = JSON.parse(
  fs.readFileSync(path.join(orchestrationDir, "runtime-static-analysis.json"), "utf8"),
);
const workerProfiles = JSON.parse(
  fs.readFileSync(path.join(orchestrationDir, "worker-profiles.json"), "utf8"),
);

const endpoints = (endpointSemantics.endpoints ?? []).map((endpoint) => ({
  endpointId: endpoint.endpoint_id,
  file: endpoint.file,
  routes: endpoint.routes ?? [],
  handler: endpoint.handler,
  workflowGraph: endpoint.workflow_graph_guess,
  runtimeActorRole: endpoint.runtime_actor_role_guess,
  runtimePurpose: endpoint.runtime_purpose,
  triggerSemantics: endpoint.trigger_semantics ?? [],
  readsProperties: endpoint.reads_properties ?? [],
  writesProperties: endpoint.writes_properties ?? [],
  traversesAssociations: endpoint.traverses_associations ?? [],
  temporalLogic: endpoint.temporal_logic ?? [],
  hubspotRepositoryCalls: endpoint.hubspot_repository_calls ?? [],
  serviceCallChainHints: endpoint.service_call_chain_hints ?? [],
  downstreamEffects: endpoint.downstream_effects ?? [],
  confidenceScore: endpoint.confidence_score ?? null,
  operationalUsefulness: endpoint.operational_usefulness ?? null,
}));

const functions = (runtimeStaticAnalysis.functions ?? []).map((fn) => ({
  functionId: fn.function_id,
  functionName: fn.function_name,
  file: fn.file,
  workflowGraph: fn.workflow_graph_guess,
  runtimeActorRole: fn.runtime_actor_role_guess,
  routes: fn.routes ?? [],
  readsProperties: fn.reads_properties ?? [],
  writesProperties: fn.writes_properties ?? [],
  writesDealstages: fn.writes_dealstages ?? [],
  traversesAssociations: fn.traverses_associations ?? [],
  temporalLogic: fn.temporal_logic ?? [],
  hubspotRepositoryCalls: fn.hubspot_repository_calls ?? [],
  serviceCallHints: fn.service_call_hints ?? [],
  evidenceScore: fn.evidence_score ?? null,
}));

const workers = (workerProfiles ?? []).map((worker) => ({
  workerName: worker.worker_name,
  workflowGraph: worker.workflow_graph,
  runtimeActorRole: worker.runtime_actor_role,
  rootTriggerEvents: worker.root_trigger_events ?? [],
  triggerSignals: worker.trigger_signals ?? [],
  readsEntities: worker.reads_entities ?? [],
  readsProperties: worker.reads_properties ?? [],
  traversesAssociations: worker.traverses_associations ?? [],
  computes: worker.computes ?? [],
  writesProperties: worker.writes_properties ?? [],
  writesDealstages: worker.writes_dealstages ?? [],
  emitsSignals: worker.emits_signals ?? [],
  downstreamWorkflows: worker.downstream_workflows ?? [],
  fanOutRisk: worker.fan_out_risk ?? null,
  temporalLogic: worker.temporal_logic ?? [],
  orchestrationRisk: worker.orchestration_risk ?? null,
  businessSemantics: worker.business_semantics ?? null,
}));

const target = path.join(root, "src", "lib", "generatedRuntimeAnalysis.ts");
const content = `// Auto-generated by scripts/generate-runtime-analysis-module.mjs.
// Source: docs/runtime-orchestration/*.json

export interface RuntimeEndpointAnalysis {
  endpointId: string;
  file: string;
  routes: string[];
  handler: string;
  workflowGraph?: string;
  runtimeActorRole?: string;
  runtimePurpose?: string;
  triggerSemantics: string[];
  readsProperties: string[];
  writesProperties: string[];
  traversesAssociations: string[];
  temporalLogic: string[];
  hubspotRepositoryCalls: string[];
  serviceCallChainHints: string[];
  downstreamEffects: string[];
  confidenceScore: number | null;
  operationalUsefulness: string | null;
}

export interface RuntimeFunctionAnalysis {
  functionId: string;
  functionName: string;
  file: string;
  workflowGraph?: string;
  runtimeActorRole?: string;
  routes: string[];
  readsProperties: string[];
  writesProperties: string[];
  writesDealstages: string[];
  traversesAssociations: string[];
  temporalLogic: string[];
  hubspotRepositoryCalls: string[];
  serviceCallHints: string[];
  evidenceScore: number | null;
}

export interface RuntimeWorkerProfile {
  workerName: string;
  workflowGraph?: string;
  runtimeActorRole?: string;
  rootTriggerEvents: string[];
  triggerSignals: string[];
  readsEntities: string[];
  readsProperties: string[];
  traversesAssociations: string[];
  computes: string[];
  writesProperties: string[];
  writesDealstages: string[];
  emitsSignals: string[];
  downstreamWorkflows: string[];
  fanOutRisk: string | null;
  temporalLogic: string[];
  orchestrationRisk: string | null;
  businessSemantics: string | null;
}

export const RUNTIME_ENDPOINT_ANALYSIS = ${JSON.stringify(endpoints, null, 2)} as RuntimeEndpointAnalysis[];

export const RUNTIME_FUNCTION_ANALYSIS = ${JSON.stringify(functions, null, 2)} as RuntimeFunctionAnalysis[];

export const RUNTIME_WORKER_PROFILES = ${JSON.stringify(workers, null, 2)} as RuntimeWorkerProfile[];
`;

fs.writeFileSync(target, content);
console.log(`Generated ${path.relative(root, target)} with ${endpoints.length} endpoints, ${functions.length} functions and ${workers.length} workers.`);
